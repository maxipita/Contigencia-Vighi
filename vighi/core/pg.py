import re
import sqlite3
import threading
from decimal import Decimal

import psycopg
from psycopg import errors

from vighi.core.d1 import Cursor, ErrorConexion, ErrorSQL, Fila, dividir_script

_hilo = threading.local()
_con_id = {}

PATRON_PRAGMA = re.compile(r"\s*PRAGMA\s+table_info\(\s*(\w+)\s*\)\s*;?\s*$", re.I)
PATRON_MAESTRA = re.compile(r"\s*SELECT\s+1\s+FROM\s+sqlite_master\s+WHERE\s+type\s*=\s*'table'\s+AND\s+name\s*=\s*'(\w+)'\s*;?\s*$", re.I)
PATRON_INSERT = re.compile(r"\s*INSERT\s+INTO\s+(\w+)", re.I)
PATRON_COMILLAS = re.compile(r"('(?:[^']|'')*')")
PATRON_DDL = re.compile(r"\s*(CREATE|ALTER|DROP)\b", re.I)


def _traducir_ddl(sql):
    sql = re.sub(r"INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT", "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", sql, flags=re.I)
    sql = re.sub(r"\bBLOB\b", "BYTEA", sql, flags=re.I)
    sql = re.sub(r"\bREAL\b", "DOUBLE PRECISION", sql, flags=re.I)
    return re.sub(r"VARCHAR\(\d+\)", "TEXT", sql, flags=re.I)


def _fuera_de_comillas(sql, funcion):
    partes = PATRON_COMILLAS.split(sql)
    return "".join(p if i % 2 else funcion(p) for i, p in enumerate(partes))


def _dialecto(trozo):
    trozo = re.sub(r"\bLIKE\b", "ILIKE", trozo, flags=re.I)
    return re.sub(r"CAST\(\s*([\w.]+)\s+AS\s+INTEGER\s*\)", r"CAST(substring(\1::text from '^[0-9]+') AS INTEGER)", trozo, flags=re.I)


def traducir(sql, con_parametros):
    if PATRON_DDL.match(sql):
        sql = _traducir_ddl(sql)
    else:
        sql = re.sub(r"([\w.]+)\s+GLOB\s+'\[0-9\]\*'", r"\1 ~ '^[0-9]'", sql, flags=re.I)
        sql = _fuera_de_comillas(sql, _dialecto)
    if con_parametros:
        return _fuera_de_comillas(sql.replace("%", "%%"), lambda p: p.replace("?", "%s"))
    return sql


def _convertir(error):
    if isinstance(error, errors.IntegrityError):
        return sqlite3.IntegrityError(str(error).splitlines()[0])
    if isinstance(error, (psycopg.OperationalError, psycopg.InterfaceError)):
        return ErrorConexion(f"No hay conexión con la base de datos: {type(error).__name__}")
    return ErrorSQL(str(error).splitlines()[0])


def _conexion_del_hilo(dsn):
    cx = getattr(_hilo, "cx", None)
    if cx is None or cx.closed or cx.broken or getattr(_hilo, "dsn", None) != dsn:
        if cx is not None and not cx.closed:
            cx.close()
        try:
            cx = psycopg.connect(dsn, autocommit=True)
        except psycopg.Error as e:
            raise ErrorConexion(f"No hay conexión con la base de datos: {type(e).__name__}") from None
        _hilo.cx, _hilo.dsn = cx, dsn
    return cx


def _tiene_id(cx, tabla):
    clave = tabla.lower()
    if clave not in _con_id:
        r = cx.execute("SELECT 1 FROM information_schema.columns WHERE table_schema=current_schema() AND table_name=%s AND column_name='id' AND is_identity='YES'",
                       (clave,)).fetchone()
        _con_id[clave] = r is not None
    return _con_id[clave]


def _valor(v):
    if isinstance(v, Decimal):
        return float(v)
    if isinstance(v, memoryview):
        return bytes(v)
    return v


class Conexion:
    def __init__(self, dsn):
        self._dsn = dsn

    def _cx(self):
        return _conexion_del_hilo(self._dsn)

    def _ejecutar(self, cx, sql, params):
        params = tuple(params or ())
        m = PATRON_PRAGMA.match(sql)
        if m:
            filas = cx.execute("SELECT column_name FROM information_schema.columns WHERE table_schema=current_schema() AND table_name=%s ORDER BY ordinal_position",
                               (m.group(1).lower(),)).fetchall()
            return Cursor([Fila(["name"], [f[0]]) for f in filas])
        m = PATRON_MAESTRA.match(sql)
        if m:
            hay = cx.execute("SELECT 1 FROM information_schema.tables WHERE table_schema=current_schema() AND table_name=%s", (m.group(1).lower(),)).fetchone()
            return Cursor([Fila(["?column?"], [1])] if hay else [])
        texto = traducir(sql, bool(params))
        retorno = False
        m = PATRON_INSERT.match(texto)
        if m and "returning" not in texto.lower() and _tiene_id(cx, m.group(1)):
            texto = texto.rstrip().rstrip(";") + " RETURNING id"
            retorno = True
        try:
            cur = cx.execute(texto, params or None)
            if cur.description:
                columnas = [d.name for d in cur.description]
                filas = [Fila(columnas, [_valor(v) for v in f]) for f in cur.fetchall()]
            else:
                filas = []
            ultimo = None
            if retorno and filas:
                ultimo, filas = filas[-1][0], []
            return Cursor(filas, ultimo, max(cur.rowcount, 0))
        except psycopg.Error as e:
            raise _convertir(e) from None

    def execute(self, sql, params=()):
        return self._ejecutar(self._cx(), sql, params)

    def lote(self, declaraciones):
        cx = self._cx()
        try:
            with cx.transaction():
                return [self._ejecutar(cx, s, p) for s, p in declaraciones]
        except psycopg.Error as e:
            raise _convertir(e) from None

    def executemany(self, sql, filas):
        filas = [tuple(f) for f in filas]
        if not filas:
            return
        cx = self._cx()
        texto = traducir(sql, True)
        try:
            with cx.transaction():
                with cx.cursor() as cur:
                    cur.executemany(texto, filas)
        except psycopg.Error as e:
            raise _convertir(e) from None

    def executescript(self, script):
        cx = self._cx()
        try:
            with cx.transaction():
                for sentencia in dividir_script(script):
                    cx.execute(traducir(sentencia, False))
        except psycopg.Error as e:
            raise _convertir(e) from None
        _con_id.clear()

    def commit(self):
        pass

    def rollback(self):
        pass

    def close(self):
        pass


def reiniciar_secuencias(c, tablas):
    cx = c._cx()
    for t in tablas:
        if _tiene_id(cx, t):
            cx.execute(f"SELECT setval(pg_get_serial_sequence('{t}', 'id'), COALESCE((SELECT MAX(id) FROM {t}), 1), (SELECT MAX(id) FROM {t}) IS NOT NULL)")
